using System;
using System.Collections.Generic;
using System.Security.Cryptography;
using System.Text;

namespace A6_HashingHMACAndStreaming.FileHash_Hmac
{
    public class FileHashHmac
    {
        private const string FilePath = "hash-demo.txt";

        public void Run_Hmac_Hashing()
        {

            CreateSampleFile();

            // -------------------------------------------------
            // SHA-256
            // -------------------------------------------------

            byte[] sha256Hash =
                CalculateSHA256(FilePath);

            Console.WriteLine(
                $"SHA-256:\n{Convert.ToHexString(sha256Hash)}");

            // -------------------------------------------------
            // SHA-512
            // -------------------------------------------------

            byte[] sha512Hash =
                CalculateSHA512(FilePath);

            Console.WriteLine(
                $"\nSHA-512:\n{Convert.ToHexString(sha512Hash)}");

            // -------------------------------------------------
            // HMAC-SHA256
            // -------------------------------------------------

            byte[] key =
                Encoding.UTF8.GetBytes(
                    "MySecretHmacKey");

            byte[] hmac =
                CalculateHMACSHA256(
                    FilePath,
                    key);

            Console.WriteLine(
                $"\nHMAC-SHA256:\n{Convert.ToHexString(hmac)}");

            // -------------------------------------------------
            // Verify HMAC with same key
            // -------------------------------------------------

            byte[] hmacAgain =
                CalculateHMACSHA256(
                    FilePath,
                    key);

            bool sameHmac =
                CryptographicOperations.FixedTimeEquals(
                    hmac,
                    hmacAgain);

            Console.WriteLine(
                $"\nSame key produces same HMAC: {sameHmac}");

            // -------------------------------------------------
            // Change the key
            // -------------------------------------------------

            byte[] differentKey =
                Encoding.UTF8.GetBytes(
                    "DifferentSecretKey");

            byte[] differentHmac =
                CalculateHMACSHA256(
                    FilePath,
                    differentKey);

            bool hmacChanged =
                !CryptographicOperations.FixedTimeEquals(
                    hmac,
                    differentHmac);

            Console.WriteLine(
                $"Changing the key changes HMAC: {hmacChanged}");

            /*
             * HASH vs HMAC
             *
             * Hash:
             *   Data -> Hash
             *
             *   A hash does not require a secret key.
             *   It can show whether data changed.
             *
             * HMAC:
             *   Data + Secret Key -> HMAC
             *
             *   Only someone possessing the secret key can
             *   generate a valid HMAC.
             *
             * Therefore:
             *
             * Hash answers:
             * "Does this data produce this digest?"
             *
             * HMAC additionally answers:
             * "Was this digest generated by someone who
             * possesses the secret key?"
             */
        }

        private void CreateSampleFile()
        {
            string content =
                "This file is used to demonstrate SHA-256, " +
                "SHA-512 and HMAC-SHA256.";

            File.WriteAllText(
                FilePath,
                content);

            Console.WriteLine(
                $"Sample file created: {FilePath}");
        }

        private byte[] CalculateSHA256(
            string filePath)
        {
            using FileStream fileStream =
                new FileStream(
                    filePath,
                    FileMode.Open,
                    FileAccess.Read);

            using SHA256 sha256 =
                SHA256.Create();

            return sha256.ComputeHash(fileStream);
        }

        private byte[] CalculateSHA512(
            string filePath)
        {
            using FileStream fileStream =
                new FileStream(
                    filePath,
                    FileMode.Open,
                    FileAccess.Read);

            using SHA512 sha512 =
                SHA512.Create();

            return sha512.ComputeHash(fileStream);
        }

        private byte[] CalculateHMACSHA256(
            string filePath,
            byte[] key)
        {
            using FileStream fileStream =
                new FileStream(
                    filePath,
                    FileMode.Open,
                    FileAccess.Read);

            using HMACSHA256 hmac =
                new HMACSHA256(key);

            return hmac.ComputeHash(fileStream);
        }
    }
}
